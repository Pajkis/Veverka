/// <summary>
/// Types of popout images that can be displayed during gameplay.
/// Used to select appropriate prefab variant in PopoutImageManager.
/// </summary>
public enum PopoutImageType
{
    NoImage,          // No popout image (default/none)
    BasicGoal,        // Basic goal popout (standard nut in goal)
    GoldenGoal,       // Golden goal popout (golden nut in golden goal)   
}
